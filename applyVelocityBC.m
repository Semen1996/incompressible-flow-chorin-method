function [u, v] = applyVelocityBC(u, v, uLid)
% APPLYVELOCITYBC Граничные условия для скорости на разнесенной сетке
%
% [u, v] = applyVelocityBC(u, v, uLid)
%
% u    - скорость по x, размер (ny+2, nx+1)
% v    - скорость по y, размер (ny+1, nx+2)
% uLid - скорость верхней крышки

    %% u
    u(:, 1)   = 0;                       % левая стенка (узлы на стенке)
    u(:, end) = 0;                       % правая стенка (узлы на стенке)
    u(1, :)   = -u(2, :);                % дно (фиктивная строка): (u_1 + u_2)/2 = 0
    u(end, :) = 2 * uLid - u(end-1, :);  % крышка (фиктивная строка): (u_N + u_N+1)/2 = uLid

    %% v
    v(1, :)   = 0;                       % дно (узлы на стенке)
    v(end, :) = 0;                       % крышка (узлы на стенке)
    v(:, 1)   = -v(:, 2);                % левая стенка (фиктивный столбец)
    v(:, end) = -v(:, end-1);            % правая стенка (фиктивный столбец)
end
